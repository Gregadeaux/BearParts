import type { Layer } from "./canvas";
import { fmtTol, upper } from "./format";
import { circle, line, polyline, pt, rect, text, type Pt } from "./primitives";
import { qrMatrix, qrRects } from "./qr";
import { DIA, textWidth, type Box } from "./text-metrics";

/** ANSI A landscape. */
export const SHEET_W = 11;
export const SHEET_H = 8.5;
export const BORDER = 0.375;

const TB_W = 4.1; // title block
const TOL_W = 1.95; // tolerance block, left of the title block
const TB_H = 1.5;
const LABEL_H = 0.055;
const VALUE_H = 0.1;

export interface TitleBlockData {
  title: string;
  drafter: string;
  date: string;
  material: string;
  thickness: string;
  quantity: string;
  scale: string;
  revision: string;
  fileName: string;
  /** shop tolerances (inches) — from the shared key-dimension constants */
  toleranceIn: number;
  holeToleranceIn: number;
  /** multi-view sheets carry the third-angle projection symbol */
  thirdAngle: boolean;
  /** part page link, printed as a QR code beside the title block */
  qrUrl?: string | null;
}

/** QR cell joined to the left of the tolerance block. */
const QR_W = 1.05;
/** QR square including its quiet zone (~0.8" of modules): scans from a printout. */
export const QR_SIZE = 0.95;

/**
 * Border, title block (bottom right), tolerance block, and numbered general
 * notes (bottom left). Returns the free region left for views.
 */
export function drawFrame(layer: Layer, d: TitleBlockData, notes: string[]): Box {
  const x1 = SHEET_W - BORDER;
  const y0 = BORDER;
  layer.path(rect(BORDER, BORDER, SHEET_W - 2 * BORDER, SHEET_H - 2 * BORDER, "medium"));

  const tbX = x1 - TB_W;
  const tolX = tbX - TOL_W;
  const top = y0 + TB_H;
  layer.path(rect(tolX, y0, TB_W + TOL_W, TB_H, "medium"));
  layer.path(line(pt(tbX, y0), pt(tbX, top), "medium"));
  // everything in the block area is occupied
  layer.occ.addBox({ x0: tolX, y0, x1, y1: top });

  // rows, bottom → top: [h, cells as [label, value, width]]
  const rows: [number, [string, string, number][]][] = [
    [0.31, [["SIZE", "A", 0.45], ["CAD FILE", d.fileName, 1.95], ["UNITS", "INCHES", 0.8], ["SHEET", "1 OF 1", 0.9]]],
    [0.32, [["DRAWN BY", d.drafter, 1.55], ["DATE", d.date, 1.0], ["SCALE", d.scale, 0.8], ["REV", d.revision, 0.75]]],
    [0.32, [["MATERIAL", d.material, 2.4], ["THICKNESS", d.thickness, 0.95], ["QTY", d.quantity, 0.75]]],
  ];
  let y = y0;
  for (const [h, cells] of rows) {
    let x = tbX;
    for (const [label, value, w] of cells) {
      cell(layer, x, y, w, h, label, value);
      x += w;
      if (x < x1 - 1e-6) layer.path(line(pt(x, y), pt(x, y + h), "thin"));
    }
    y += h;
    layer.path(line(pt(tbX, y), pt(x1, y), "thin"));
  }
  // title row
  layer.text(text("TITLE", pt(tbX + 0.05, top - 0.05), LABEL_H, { valign: "top" }));
  const title = upper(d.title);
  layer.text(text(title, pt(tbX + 0.08, y + (top - y) / 2 - 0.02), fitSize(title, 0.16, TB_W - 0.16, true), { valign: "middle", bold: true }));
  layer.text(text("GENERATED BY BEARPARTS", pt(x1 - 0.05, top - 0.05), LABEL_H, { align: "right", valign: "top" }));

  toleranceBlock(layer, tolX, y0, top, d);
  if (d.qrUrl) qrCell(layer, tolX - QR_W, y0, top, d.qrUrl);
  drawNotes(layer, BORDER + 0.12, y0 + 0.08, notesWidth(Boolean(d.qrUrl)), notes);
  return frameRegion(notes, Boolean(d.qrUrl));
}

/** Vector QR (one filled rectangle per run of dark modules) with its caption. */
function qrCell(layer: Layer, x: number, y0: number, top: number, url: string) {
  layer.path(rect(x, y0, QR_W, top - y0, "medium"));
  layer.occ.addBox({ x0: x, y0, x1: x + QR_W, y1: top });
  const qx = x + (QR_W - QR_SIZE) / 2;
  const qy = top - 0.04 - QR_SIZE;
  // a hair of overlap between rows so viewers never show seams
  for (const r of qrRects(qrMatrix(url), qx, qy, QR_SIZE)) {
    layer.path(polyline([pt(r.x, r.y - 0.0008), pt(r.x + r.w, r.y - 0.0008), pt(r.x + r.w, r.y + r.h), pt(r.x, r.y + r.h)], true, "thin", true), false);
  }
  layer.text(text("SCAN FOR PART FILE", pt(x + QR_W / 2, y0 + (qy - y0) / 2), 0.055, { align: "center", valign: "middle", bold: true }));
}

const notesWidth = (qr: boolean) => SHEET_W - 2 * BORDER - TB_W - TOL_W - 0.3 - (qr ? QR_W : 0);
const NOTE_H = 0.1;
const NOTE_LEAD = 0.17;

/** The free area for views, given the notes that will be printed (and whether a QR cell narrows them). */
export function frameRegion(notes: string[], qr = false): Box {
  const lines = notes.length === 0 ? 0 : wrapNotes(notes, notesWidth(qr)).reduce((s, l) => s + l.length, 0) + 1;
  const notesTop = BORDER + 0.08 + (lines > 0 ? (lines - 1) * NOTE_LEAD + NOTE_H : 0);
  return {
    x0: BORDER + 0.1,
    y0: Math.max(BORDER + TB_H, notesTop) + 0.15,
    x1: SHEET_W - BORDER - 0.1,
    y1: SHEET_H - BORDER - 0.1,
  };
}

const wrapNotes = (notes: string[], width: number) =>
  notes.map((n) => wrapText(upper(n), NOTE_H, width - textWidth("10. ", NOTE_H)));

function cell(layer: Layer, x: number, y: number, w: number, h: number, label: string, value: string) {
  layer.text(text(label, pt(x + 0.04, y + h - 0.04), LABEL_H, { valign: "top" }));
  let v = upper(value) || "—";
  const size = fitSize(v, VALUE_H, w - 0.1);
  // still too long at the smallest size: keep both ends, elide the middle
  while (textWidth(v, size) > w - 0.1 + 1e-6 && v.length > 8) {
    const keep = v.replace("...", "");
    const cut = Math.floor(keep.length / 2);
    v = `${keep.slice(0, cut - 1)}...${keep.slice(cut + 1)}`;
  }
  layer.text(text(v, pt(x + 0.05, y + 0.07), size));
}

/** Shrink text (not below 60%) so it fits a cell width. */
function fitSize(s: string, size: number, width: number, bold = false): number {
  const w = textWidth(s, size, bold);
  return w <= width ? size : Math.max(size * 0.6, (size * width) / w);
}

function toleranceBlock(layer: Layer, x: number, y0: number, top: number, d: TitleBlockData) {
  const h = 0.075;
  const lines: [string, boolean][] = [
    ["UNLESS OTHERWISE SPECIFIED:", true],
    ["DIMENSIONS ARE IN INCHES", false],
    ["TOLERANCES:", false],
    [`   .XXX  ${fmtTol(d.toleranceIn)}`, false],
    [`   HOLE ${DIA}  ${fmtTol(d.holeToleranceIn)}`, false],
    ["DO NOT SCALE DRAWING", false],
  ];
  let y = top - 0.08;
  for (const [s, bold] of lines) {
    layer.text(text(s, pt(x + 0.08, y), h, { valign: "top", bold }));
    y -= 0.15;
  }
  if (d.thirdAngle) {
    layer.path(line(pt(x, y0 + 0.42), pt(x + TOL_W, y0 + 0.42), "thin"));
    layer.text(text("THIRD ANGLE", pt(x + 0.08, y0 + 0.25), 0.07, { valign: "bottom" }));
    layer.text(text("PROJECTION", pt(x + 0.08, y0 + 0.1), 0.07, { valign: "bottom" }));
    projectionSymbol(layer, pt(x + 1.5, y0 + 0.21));
  }
}

/** Third-angle symbol: truncated-cone elevation, end view to its right. */
function projectionSymbol(layer: Layer, c: Pt) {
  const big = 0.13;
  const small = 0.065;
  const lx = c.x - 0.36;
  const rx = c.x - 0.1;
  layer.path(polyline([pt(lx, c.y - big), pt(rx, c.y - small), pt(rx, c.y + small), pt(lx, c.y + big)], true, "thin"));
  const cc = pt(c.x + 0.12, c.y);
  layer.path(circle(cc, big, "thin"));
  layer.path(circle(cc, small, "thin"));
  layer.path(line(pt(lx - 0.04, c.y), pt(cc.x + big + 0.04, c.y), "thin"));
  layer.path(line(pt(cc.x, c.y - big - 0.04), pt(cc.x, c.y + big + 0.04), "thin"));
}

/** Greedy word wrap to a width at the given capital height. */
export function wrapText(s: string, size: number, width: number): string[] {
  const words = s.split(/\s+/).filter(Boolean);
  const out: string[] = [];
  let cur = "";
  for (const w of words) {
    const next = cur ? `${cur} ${w}` : w;
    if (cur && textWidth(next, size) > width) {
      out.push(cur);
      cur = w;
    } else cur = next;
  }
  if (cur) out.push(cur);
  return out;
}

/** Numbered general notes, bottom-anchored at `bottom`. */
function drawNotes(layer: Layer, x: number, bottom: number, width: number, notes: string[]) {
  if (notes.length === 0) return;
  const h = NOTE_H;
  const indent = textWidth("10. ", h);
  const wrapped = notes.map((n) => wrapText(upper(n), h, width - indent));
  const total = wrapped.reduce((s, l) => s + l.length, 0) + 1;
  let y = bottom + (total - 1) * NOTE_LEAD;
  layer.text(text("NOTES:", pt(x, y), h, { bold: true }));
  wrapped.forEach((lines, i) => {
    y -= NOTE_LEAD;
    layer.text(text(`${i + 1}.`, pt(x, y), h));
    for (const [j, l] of lines.entries()) {
      if (j > 0) y -= NOTE_LEAD;
      layer.text(text(l, pt(x + indent, y), h));
    }
  });
}
